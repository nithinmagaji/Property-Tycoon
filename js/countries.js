export function applyCountryToBoard(board, countryKey) {
  const key = COUNTRY_OPTIONS.includes(countryKey) ? countryKey : "USA";
  const names = TEMPLATES[key] || TEMPLATES.USA;
  PROPERTY_INDICES.forEach((idx, i) => {
    if (board[idx] && names[i]) board[idx][0] = names[i];
  });
  return key;
}
